  update: function (api, dt, t) {
    var s = api.state;
    s.K.update(dt);
    if (!api.reduceMotion) s.sun.rotation.z += dt * 0.2;
    /* baagh hatne par: hiran badhte hain, ghaas ghat-ti hai */
    s.eco += ((s.noTigers ? 1 : 0) - s.eco) * Math.min(1, dt * 0.6);
    var nExtra = Math.round(s.eco * s.extraDeer.length);
    s.extraDeer.forEach(function (d, i) { d.visible = i < nExtra; });
    var gs = 1 - 0.75 * s.eco;
    s.blades.forEach(function (b, i) {
      var k = gs * (0.8 + 0.2 * Math.sin(t * 2 + i));
      b.scale.y = Math.max(0.1, k);
      b.position.y = b.userData.h * b.scale.y / 2;
    });
    /* sab pattiyon ka ek hi material hai */
    s.blades[0].material.color.setRGB(0.25 + 0.4 * s.eco, 0.6 - 0.15 * s.eco, 0.2);
  }
