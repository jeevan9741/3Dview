  update: function (api, dt, t) {
    var s = api.state;
    s.K.update(dt);
    if (s.bee.visible && !api.reduceMotion) s.wings.forEach(function (w, i) { w.rotation.x = Math.sin(t * 40 + i * Math.PI) * 0.6; });
    if (!s.anim) return;
    s.anim.t += dt;
    var T = s.anim.t;
    if (s.anim.kind === "bee") {
      /* 3 hisse: phool tak (2.4s), anther se stigma (2s), door udna (1.8s) */
      var D = [2.4, 2.0, 1.8], seg = 0, local = T;
      while (seg < 3 && local > D[seg]) { local -= D[seg]; seg++; }
      if (seg >= 3) { s.bee.visible = false; s.finish(); return; }
      s.bee.visible = true;
      var k = Math.min(1, local / D[seg]);
      k = k * k * (3 - 2 * k);
      var c = s.beePaths[seg];
      s.bee.position.copy(c.getPointAt(k));
      var tg = c.getTangentAt(Math.min(0.999, k));
      s.bee.rotation.y = Math.atan2(-tg.z, tg.x);
      if (seg >= 1) s.beePollen.visible = true;
      if (seg === 2) s.stigmaPollen.visible = true;
    } else if (s.anim.kind === "tube") {
      var p = Math.min(1, T / 3.2);
      s.tube.geometry.setDrawRange(0, Math.floor(s.tubeTotal * p / 3) * 3);
      if (p >= 1) {
        s.target.material.emissiveIntensity = 0.9;
        if (T > 3.8) s.finish();
      }
    } else if (s.anim.kind === "fruit") {
      var f = Math.min(1, T / 3.5);
      s.applyFruit(f * f * (3 - 2 * f));
      if (f >= 1) s.finish();
    }
  }
