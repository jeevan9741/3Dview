    var oleM = mat(0xfff3d6, { rough: 0.4 });
    s.ovuleMeshes = [];
    /* pehle beejand ki apni chamak (glow) taaki nishechan par woh chamke; engine use nahi chhedta */
    var targetM = mat(0xfff3d6, { rough: 0.4, glow: 0xff7a00, glowLevel: 0 });
    [[0.12, 0.22, 0.08], [-0.13, 0.05, 0.1], [0.1, -0.15, -0.12], [-0.08, -0.28, 0.02], [0.02, 0.0, -0.18]].forEach(function (p, j) {
      var m = K.blob(0.085, j === 0 ? targetM : oleM, 1, 1.25, 1, 14);
      m.position.set(p[0], p[1], p[2]);
      ovules.add(m);
      s.ovuleMeshes.push(m);
    });
    ovary.add(ovules);
    api.addPart("ovule", ovules, null, null, { label: V(0.12, 0.22, 0.08) });

