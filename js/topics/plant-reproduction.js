    style.add(api.cyl(0.045, 0.06, 1.3, mat(0xa6dc7c, { rough: 0.5 }), 0, 0.65, 0, 12));
    api.addPart("style", style, V(0, 0.92, 0), null, { label: V(0, 0.7, 0) });
    s.style = style;

    var stigma = new THREE.Group();
    var stgM = mat(0xd5e85a, { rough: 0.35 });
    for (i = 0; i < 3; i++) {
      a = i / 3 * Math.PI * 2;
      var lobe = K.blob(0.1, stgM, 1, 0.7, 1, 12);
      lobe.position.set(Math.cos(a) * 0.08, 0, Math.sin(a) * 0.08);
      stigma.add(lobe);
    }
    s.stigmaPollen = new THREE.Group();
    for (i = 0; i < 6; i++) s.stigmaPollen.add(api.sphere(0.035, polM, (Math.random() - 0.5) * 0.2, 0.07, (Math.random() - 0.5) * 0.2, 8));
    s.stigmaPollen.visible = false;
